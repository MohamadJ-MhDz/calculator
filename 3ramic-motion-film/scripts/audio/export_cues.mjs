// 3RAMIC — exports the action cues of src/cues.ts (computed from the recorded dialogue)
// to production/cues.json, so the sound design fires on exactly the frames the picture
// animates to. src/cues.ts stays the only place where a cue is defined.
//
//     node scripts/audio/export_cues.mjs
import { buildSync } from "esbuild";
import { createRequire } from "node:module";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
// built inside node_modules so the bundle resolves react/remotion from the project
const dir = join(root, "node_modules", ".cache", "3ramic-cues");
mkdirSync(dir, { recursive: true });
const out = join(dir, "cues.cjs");
try {
  buildSync({
    entryPoints: [join(root, "src", "cues.ts")],
    bundle: true,
    platform: "node",
    format: "cjs",
    outfile: out,
    external: ["react", "remotion"],
    logLevel: "error",
  });
  const require = createRequire(out);
  const cues = require(out);
  const data = { note: "Generated by scripts/audio/export_cues.mjs from src/cues.ts — do not edit.", fps: 30 };
  for (const [k, v] of Object.entries(cues)) {
    if (k === "SPOKEN") continue;
    data[k] = v;
  }
  writeFileSync(join(root, "production", "cues.json"), JSON.stringify(data, null, 1) + "\n");
  console.log("wrote production/cues.json:", Object.keys(data).filter((k) => k !== "note" && k !== "fps").join(", "));
} finally {
  rmSync(dir, { recursive: true, force: true });
}
